//! # Dual 8259A Programmable Interrupt Controller (PIC)
//!
//! Provides hardware-level configuration, interrupt vector remapping, masking,
//! and End-Of-Interrupt (`EOI`) dispatch for legacy PC/AT chipsets and emulators.

/// Primary (Master) PIC command I/O port.
pub const PIC1_COMMAND: u16 = 0x20;
/// Primary (Master) PIC data I/O port.
pub const PIC1_DATA: u16 = 0x21;

/// Secondary (Slave) PIC command I/O port.
pub const PIC2_COMMAND: u16 = 0xA0;
/// Secondary (Slave) PIC data I/O port.
pub const PIC2_DATA: u16 = 0xA1;

/// Initialization Command Word 1: requires ICW4.
pub const ICW1_ICW4: u8 = 0x01;
/// Initialization Command Word 1: initialize controller.
pub const ICW1_INIT: u8 = 0x10;
/// Initialization Command Word 4: 8086/88 mode operation.
pub const ICW4_8086: u8 = 0x01;

/// End-Of-Interrupt (`EOI`) acknowledgment command.
pub const PIC_EOI: u8 = 0x20;

/// Mask all IRQ lines on a PIC controller.
pub const PIC_MASK_ALL: u8 = 0xFF;

/// Dual cascaded 8259 PIC abstraction for x86 platform initialization.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ChainedPic {
    /// Vector offset for Master PIC (typically `0x20`).
    pub master_offset: u8,
    /// Vector offset for Slave PIC (typically `0x28`).
    pub slave_offset: u8,
}

impl ChainedPic {
    /// Create a new dual 8259 PIC descriptor with designated interrupt offsets.
    #[must_use]
    pub const fn new(master_offset: u8, slave_offset: u8) -> Self {
        Self {
            master_offset,
            slave_offset,
        }
    }

    /// Check if a given interrupt vector was generated by either the Master or Slave PIC.
    #[must_use]
    pub const fn handles_interrupt(&self, vector: u8) -> bool {
        (vector >= self.master_offset && vector < self.master_offset + 8)
            || (vector >= self.slave_offset && vector < self.slave_offset + 8)
    }

    /// Compute the required `EOI` commands for a handled interrupt vector.
    ///
    /// Returns `(eoi_master, eoi_slave)` booleans indicating which controllers need an `EOI`.
    #[must_use]
    pub const fn compute_eoi(&self, vector: u8) -> (bool, bool) {
        if vector >= self.slave_offset && vector < self.slave_offset + 8 {
            (true, true)
        } else if vector >= self.master_offset && vector < self.master_offset + 8 {
            (true, false)
        } else {
            (false, false)
        }
    }
}
