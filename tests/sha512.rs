#[test]
fn sha512_streamed_multi_chunk() {
    let mut hasher = Sha512::new();
    hasher.update(binding_ma(b"a"));
    hasher.update(binding_ma(b""));
    hasher.update(binding_ma(b"bc"));
    let digest = hasher.finalize();
    assert!(digest_eq512(&digest, &sha512(b"abc")));
    let mut hasher384 = Sha384::new();
    hasher384.update(b"ab");
    hasher384.update(b"c");
    assert!(digest_eq384(&hasher384.finalize(), &sha384(b"abc")));
    assert!(!digest_eq512(&sha512(b"abc"), &sha512(b"abd")));
    assert!(!digest_eq384(&sha384(b"abc"), &sha384(b"abd")));
}

fn binding_ma(bytes: &[u8]) -> &[u8] {
    bytes
}
