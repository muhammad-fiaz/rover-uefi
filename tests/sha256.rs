//! Native SHA-256 tests with known-answer vectors.
use rover_uefi::protocols::security::sha256::{Sha256, digest_eq, sha256};

fn hex(bytes: &[u8]) -> [u8; 64] {
    let mut out = [0_u8; 64];
    for (i, b) in bytes.iter().enumerate() {
        out[i * 2] = b"0123456789abcdef"[(b >> 4) as usize];
        out[i * 2 + 1] = b"0123456789abcdef"[(b & 0x0f) as usize];
    }
    out
}

#[test]
fn empty_digest_matches_vector() {
    let d = sha256(b"");
    assert_eq!(
        hex(&d),
        hex(&[
            0xe3, 0xb0, 0xc4, 0x42, 0x98, 0xfc, 0x1c, 0x14, 0x9a, 0xfb, 0xf4, 0xc8, 0x99, 0x6f,
            0xb9, 0x24, 0x27, 0xae, 0x41, 0xe4, 0x64, 0x9b, 0x93, 0x4c, 0xa4, 0x95, 0x99, 0x1b,
            0x78, 0x52, 0xb8, 0x55
        ])
    );
}

#[test]
fn abc_digest_and_streaming_match() {
    let expected = [
        0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40, 0xde, 0x5d, 0xae, 0x22,
        0x23, 0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c, 0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00,
        0x15, 0xad,
    ];
    assert!(digest_eq(&sha256(b"abc"), &expected));
    let mut h = Sha256::new();
    h.update(b"ab");
    h.update(b"c");
    assert!(digest_eq(&h.finalize(), &expected));
    assert!(!digest_eq(&sha256(b"abc"), &sha256(b"abd")));
}
